"""Position & PnL REST endpoint.

GET /api/v1/positions — one row per symbol the caller has traded:
position size (from balances, locked included), moving-average cost,
realized PnL, last price (kline cache close, fallback: own last fill),
and unrealized PnL.
"""
from __future__ import annotations

import json
from decimal import Decimal

from fastapi import APIRouter, Depends, Request

from app.api.deps import AuthenticatedUser, SessionDep, require_permission
from app.redis_client import get_redis, klines
from app.repositories.balance_repo import BalanceRepository
from app.repositories.trade_repo import TradeRepository
from app.services.position_service import compute_positions

router = APIRouter(prefix="/positions", tags=["positions"])


@router.get("", dependencies=[Depends(require_permission("read"))])
async def list_positions(
    request: Request,
    user_id: AuthenticatedUser,
    session: SessionDep,
) -> dict:
    trade_repo = TradeRepository(session)
    trades = await trade_repo.list_all_user_trades(user_id)
    agg = compute_positions(trades, user_id)
    if not agg:
        return {"positions": []}

    balance_repo = BalanceRepository(session)
    balances = {b.asset: b for b in await balance_repo.get_all_for_user(user_id)}

    redis = get_redis()
    rows = []
    for symbol, a in sorted(agg.items()):
        base = symbol.split("/")[0]

        last_price = Decimal("0")
        try:
            latest = await redis.zrevrange(klines.kline_key(symbol, "1m"), 0, 0, withscores=True)
            if latest:
                last_price = Decimal(json.loads(latest[0][0]).get("c", 0))
        except Exception:  # cache miss / corrupt member: fall back below
            last_price = Decimal("0")
        if last_price <= 0:
            last_price = a.last_trade_price

        bal = balances.get(base)
        qty = Decimal(bal.total_balance) if bal else a.quantity
        locked = Decimal(bal.locked_balance) if bal else Decimal("0")

        unrealized = a.quantity * (last_price - a.avg_cost)
        rows.append({
            "symbol": symbol,
            "base": base,
            # position = delta generated by the user's own trading; balances
            # in this testbed include endowed funds, which are not a position
            "quantity": float(a.quantity),
            "balance": float(qty),
            "locked": float(locked),
            "avg_cost": float(a.avg_cost),
            "last_price": float(last_price),
            "unrealized_pnl": float(unrealized),
            "realized_pnl": float(a.realized_pnl),
            "position_value": float(a.quantity * last_price),
        })
    return {"positions": rows}
